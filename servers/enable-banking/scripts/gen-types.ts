/**
 * Regenerate src/domain/generated/enablebanking.ts from the OpenAPI description
 * Enable Banking publishes for its own API.
 *
 *   npm run gen:types -w @foreverworks/mcp-enable-banking
 *
 * The source is linked from the API reference (https://enablebanking.com/docs/api/reference/,
 * "OpenAPI spec of Enable Banking API"). Two options, both deliberate:
 *
 * - `immutable`: every property and array is readonly, so the compiler, not a
 *   comment, says nothing here edits a response in place.
 * - `defaultNonNullable: false`: a field the schema gives a default stays
 *   optional. openapi-typescript's default would make it required, which on a
 *   request body forces fields (credentials_autosubmit, access.balances) that
 *   the calls working in production have never sent.
 *
 * Read the diff before committing a regeneration: a field that turned optional
 * is a place where the code has to say what it does without it.
 */
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

const SOURCE = "https://enablebanking.com/docs/api/reference/enablebanking-api.yaml";
const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "domain", "generated", "enablebanking.ts");

/** `info.version` names the build of the spec, which is what tells two generations apart. */
const specVersion = (yaml: string): string => /^info:\n(?:[ ].*\n)*?[ ]+version: (.+)$/m.exec(yaml)?.[1]?.trim() ?? "unknown";

const main = async (): Promise<void> => {
  const response = await fetch(SOURCE);
  if (!response.ok) throw new Error(`${SOURCE} answered ${response.status}`);
  const yaml = await response.text();
  const ast = await openapiTS(yaml, { immutable: true, defaultNonNullable: false });
  const header = [
    "/**",
    " * Enable Banking's API wire types, GENERATED by openapi-typescript. Do not edit by hand:",
    " * run `npm run gen:types` in servers/enable-banking (scripts/gen-types.ts).",
    " *",
    ` * Source:    ${SOURCE}`,
    ` * Spec:      info.version ${specVersion(yaml)}`,
    ` * Generated: ${new Date().toISOString().slice(0, 10)}`,
    " */",
    "",
  ].join("\n");
  await mkdir(dirname(OUT), { recursive: true });
  await writeFile(OUT, `${header}${astToString(ast)}`);
  console.log(`wrote ${OUT} (spec ${specVersion(yaml)})`);
};

main().catch((error: unknown) => {
  console.error(error);
  process.exit(1);
});
